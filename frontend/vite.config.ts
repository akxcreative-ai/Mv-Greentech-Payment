// Custom plugin to ensure our custom financial service worker is preserved in production build
function preserveCustomServiceWorker() {
  return {
    name: 'preserve-custom-sw',
    closeBundle() {
      const srcSw = path.resolve(__dirname, 'public/sw.js');
      const distSw = path.resolve(__dirname, 'dist/sw.js');
      if (fs.existsSync(srcSw)) {
        fs.copyFileSync(srcSw, distSw);
        console.log('[Build] Preserved custom financial service worker at dist/sw.js');
      }
    },
  };
}

